// Saves what the live Google Merchant feeds say into lib/data/merchantFeedBaseline.ts:
// each product's Merchant ID, title, description, image and GTIN, none of which
// the catalog holds. See MerchantBaselineRow in lib/merchantFeed.ts for why.
//
//   node scripts/build-merchant-feed-baseline.mjs [folder holding buy.xml, rental.xml, rent-to-own.xml]
//
// Run once, against the WordPress feeds (last: 2026-11-02). Once the domain serves
// this app those URLs answer with this app's own output, so re-running only repeats
// what is already saved. Without a folder, it downloads them.
import fs from 'node:fs'
import zlib from 'node:zlib'
import nextEnv from '@next/env'

nextEnv.loadEnvConfig(process.cwd(), true, { info() {}, error() {} })

const LIVE = 'https://onsitestorage.com/wp-content/uploads'
const SOURCES = ['buy', 'rental', 'rent-to-own']
const OUT = 'lib/data/merchantFeedBaseline.ts'
const folder = process.argv[2]

async function readFeed(source) {
  if (folder) return fs.readFileSync(`${folder}/${source}.xml`, 'utf8')
  const res = await fetch(`${LIVE}/${source}-google-shopping.xml`)
  if (!res.ok) throw new Error(`${source}: HTTP ${res.status}`)
  return res.text()
}

/** handle → product_id, for every product in the catalog. */
async function catalogIds() {
  const url = `${process.env.ELASTIC_URL.replace(/\/$/, '')}/${process.env.NEXT_PUBLIC_SEARCH_INDEX}/_search`
  const ids = new Map()
  let after
  for (;;) {
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `ApiKey ${process.env.ELASTIC_API_KEY}` },
      body: JSON.stringify({
        size: 1000,
        _source: ['product_id', 'handle'],
        sort: [{ product_id: 'asc' }],
        query: { match_all: {} },
        ...(after ? { search_after: after } : {}),
      }),
    })
    if (!res.ok) throw new Error(`Elasticsearch: HTTP ${res.status}`)
    const hits = (await res.json()).hits.hits
    if (!hits.length) return ids
    for (const hit of hits) ids.set(hit._source.handle, hit._source.product_id)
    after = hits[hits.length - 1].sort
  }
}

const tag = (item, name) => {
  const open = `<g:${name}>`
  const start = item.indexOf(open)
  if (start < 0) return ''
  const from = start + open.length
  return item.slice(from, item.indexOf(`</g:${name}>`, from))
}

const ids = await catalogIds()
const baseline = {}
let unmatched = 0
for (const source of SOURCES) {
  for (const item of (await readFeed(source)).split('<item>').slice(1)) {
    const handle = tag(item, 'link').split('/').filter(Boolean).pop()
    const productId = ids.get(handle)
    if (productId === undefined) {
      unmatched++
      continue
    }
    baseline[productId] = { i: tag(item, 'id'), t: tag(item, 'title'), d: tag(item, 'description'), m: tag(item, 'image_link'), g: tag(item, 'gtin') }
  }
}

const compressed = zlib.brotliCompressSync(JSON.stringify(baseline)).toString('base64')
fs.writeFileSync(
  OUT,
  `// Generated by scripts/build-merchant-feed-baseline.mjs. Do not edit: brotli-compressed\n` +
    `// JSON of MerchantBaseline (lib/merchantFeed.ts), base64. Imported only by the feed\n` +
    `// generator (services/merchantFeed.service.ts), so it stays out of every page.\n` +
    `export const MERCHANT_FEED_BASELINE = '${compressed}'\n`,
)
console.log(`${Object.keys(baseline).length} products saved to ${OUT} (${(compressed.length / 1024).toFixed(0)} KB); ${unmatched} not in the catalog`)
