#!/usr/bin/env node
// Writes lib/data/allCityLists.ts: the "Popular Cities in <state>" and "View
// all cities in <state>" lists the native /all-city/ pages show, for the
// states named on the command line.
//
//   node scripts/extract-all-city-lists.mjs FL GA TX MI
//
// WordPress builds both lists from tags on its "Cities" posts:
//   popular-cities-<depot>     listed under "Popular Cities in <state>"
//   view-all-cities-<depot>    listed under "View all cities in <state>"
// A tag's state is its last two letters (popular-cities-miami-fl, view-all-cities-ga).
// Both lists are sorted by the city's name; the page itself is left out at render.
// REST API only (posts filtered by tag), no page downloads.

import fs from 'node:fs'
import path from 'node:path'

const WP = 'https://old.onsitestorage.com/wp-json/wp/v2'
const states = process.argv.slice(2).map((s) => s.toUpperCase())
if (!states.length) throw new Error('usage: node scripts/extract-all-city-lists.mjs FL GA TX MI')
const OUT = path.resolve('lib/data/allCityLists.ts')

const NAMED = { amp: '&', quot: '"', apos: "'", lt: '<', gt: '>', nbsp: ' ' }
const decode = (s) =>
  s
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&([a-z]+);/gi, (m, name) => NAMED[name.toLowerCase()] ?? m)
    .trim()

async function getAll(url) {
  const items = []
  for (let page = 1; ; page++) {
    const res = await fetch(`${url}&per_page=100&page=${page}`, { signal: AbortSignal.timeout(120_000) })
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
    items.push(...(await res.json()))
    if (page >= Number(res.headers.get('x-wp-totalpages') ?? 1)) return items
  }
}

const tags = await getAll(`${WP}/tags?_fields=id,slug`)
const stateOf = (slug) => slug.slice(-2).toUpperCase()

async function citiesTagged(prefix, state) {
  const ids = tags.filter((t) => t.slug.startsWith(prefix) && stateOf(t.slug) === state).map((t) => t.id)
  if (!ids.length) return []
  const posts = await getAll(`${WP}/all-city?tags=${ids.join(',')}&_fields=slug,title`)
  return posts
    .map((p) => [p.slug, decode(p.title.rendered)])
    .sort((a, b) => a[1].localeCompare(b[1], 'en') || a[0].localeCompare(b[0], 'en'))
}

const lists = {}
for (const state of states) {
  lists[state] = { popular: await citiesTagged('popular-cities-', state), viewAll: await citiesTagged('view-all-cities-', state) }
  console.log(`${state}: ${lists[state].popular.length} popular, ${lists[state].viewAll.length} in view-all`)
}

const body = Object.entries(lists)
  .map(([state, { popular, viewAll }]) => {
    const rows = (list) => list.map(([slug, city]) => `    [${JSON.stringify(slug)}, ${JSON.stringify(city)}],`).join('\n')
    return `  ${state}: {\n    popular: [\n${rows(popular)}\n    ],\n    viewAll: [\n${rows(viewAll)}\n    ],\n  },`
  })
  .join('\n')

fs.writeFileSync(
  OUT,
  `// Generated by scripts/extract-all-city-lists.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
import type { AllCityState } from '@/types/allCity'

/** [slug, city] pairs, sorted by city as WordPress sorted them. */
type CityList = readonly (readonly [slug: string, city: string])[]

export const ALL_CITY_LISTS: Readonly<Partial<Record<AllCityState, { popular: CityList; viewAll: CityList }>>> = {
${body}
}
`,
)
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${Math.round(fs.statSync(OUT).size / 1024)} KB)`)
