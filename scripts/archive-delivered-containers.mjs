// One-off: copies WordPress's "Recently Delivered Containers" (the
// onsite-delivered-containers plugin's shortcode on the old homepage) into
// lib/data/deliveredContainersArchive.ts.
//
// Why: the plugin's records exist only in WordPress, and the backend's
// delivered list starts from orders, so it has none of them. 616 records on
// 2026-11-11, dated 26 Jan 2024 to 9 Nov 2026, photos on the CDN.
//
// Not part of the build: WordPress is going away, and the copy is the record
// from then on. Run it again only to re-take the copy while WordPress is up:
//
//   node scripts/archive-delivered-containers.mjs [url]
//
// It refuses to write fewer records than the file already holds, so a broken
// page cannot empty the archive.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const SOURCE = process.argv[2] ?? 'https://old.onsitestorage.com/'
const target = new URL('../lib/data/deliveredContainersArchive.ts', import.meta.url)

const decode = (s) =>
  s
    .replace(/&#0?38;|&amp;/g, '&')
    .replace(/&#8217;|&#039;|&#39;/g, "'")
    .replace(/&#8211;/g, '–')
    .replace(/&quot;/g, '"')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

/** "November 9, 2026" → "2026-11-09", read as a calendar date (no time zone). */
function isoDate(text) {
  const m = text.match(/^([A-Za-z]+)\s+(\d{1,2}),\s*(\d{4})$/)
  if (!m) return null
  const month = new Date(`${m[1]} 1, 2000`).getMonth() + 1
  if (!month) return null
  return `${m[3]}-${String(month).padStart(2, '0')}-${m[2].padStart(2, '0')}`
}

/** A stable id from the photo's path: ".../uploads/2026/11/03075537/portland.png" → "wp-2026-11-03075537-portland". */
function idFor(image, i) {
  const path = image.split('/wp-content/uploads/')[1]
  return path ? `wp-${path.replace(/\.[a-z0-9]+$/i, '').replace(/[^a-zA-Z0-9]+/g, '-').toLowerCase()}` : `wp-${i}`
}

const res = await fetch(SOURCE, { headers: { 'User-Agent': 'Mozilla/5.0 (archive of delivered containers)' }, signal: AbortSignal.timeout(60_000) })
if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`)
const html = await res.text()

const start = html.indexOf('id="deliveredContainers"')
if (start < 0) throw new Error('no #deliveredContainers on the page')
const rest = html.slice(start)
const block = rest.slice(0, rest.indexOf('elementor-element', 50))

const records = []
const card = /background-image:\s*url\(([^)]+)\)[\s\S]*?fa-list-alt"><\/i>\s*([^<]*)<[\s\S]*?fa-calendar"><\/i>\s*([^<]*)<[\s\S]*?fa-map-marker-alt"><\/i>\s*([^<]*)</g
for (const [i, m] of [...block.matchAll(card)].entries()) {
  const image = m[1].trim().replace(/^['"]|['"]$/g, '')
  const deliveredOn = isoDate(decode(m[3]))
  if (!deliveredOn) throw new Error(`card ${i}: unreadable date "${m[3]}"`)
  records.push({ id: idFor(image, i), title: decode(m[2]), deliveredOn, location: decode(m[4]), image })
}

if (new Set(records.map((r) => r.id)).size !== records.length) throw new Error('duplicate ids')
if (existsSync(target)) {
  const had = (readFileSync(target, 'utf8').match(/"id":/g) ?? []).length
  if (records.length < had) throw new Error(`found ${records.length} records, the archive holds ${had}: not overwriting`)
}

records.sort((a, b) => b.deliveredOn.localeCompare(a.deliveredOn) || a.id.localeCompare(b.id))
const body = `// Generated by scripts/archive-delivered-containers.mjs from ${SOURCE}
// The WordPress plugin's "Recently Delivered Containers", copied once; the
// plugin's records exist nowhere else. Edit or hide records from
// Admin → Delivered Containers rather than here. Server-only: read through
// services/deliveredContainer.service.ts, never imported by browser code.
import type { ArchivedDelivery } from '@/types/deliveredContainer'

export const DELIVERED_ARCHIVE_TAKEN_AT = '${new Date().toISOString()}'

export const DELIVERED_CONTAINERS_ARCHIVE: readonly ArchivedDelivery[] = [
${records.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
]
`
writeFileSync(target, body)
console.log(`wrote ${records.length} records (${records.at(-1).deliveredOn} to ${records[0].deliveredOn}) to lib/data/deliveredContainersArchive.ts`)
