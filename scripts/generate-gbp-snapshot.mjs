// Writes lib/data/gbpSnapshot.ts: the GBP pages' published records (every
// location page, the shared content, the template) as Redis holds them at
// build time.
//
// Why: when Redis is unreachable, the GBP pages fall back. Without this the
// fallback is the code seed (lib/data/gbp*.ts), which is only as current as
// its last commit, so every edit published in /admin/gbp since then would
// vanish during an outage. With it, the fallback is the published content as
// of the last deploy; the seed stays the last resort (services/gbp.service.ts).
//
// Runs before `next build` (package.json), but only on Vercel or with
// GBP_SNAPSHOT=1: the checked-in file is the empty stub, and a local build
// would otherwise leave it rewritten in the working tree. Never fails the
// build: if Redis can't be read, the file is left as it is.
import { readFileSync, writeFileSync } from 'node:fs'

if (!process.env.VERCEL && process.env.GBP_SNAPSHOT !== '1') {
  console.log('lib/data/gbpSnapshot.ts: skipped (not on Vercel; GBP_SNAPSHOT=1 to force)')
  process.exit(0)
}

const { GBP_PAGES } = await import('../lib/data/gbpPages.ts')

function env(name) {
  if (process.env[name]) return process.env[name]
  try {
    const line = readFileSync(new URL('../.env.local', import.meta.url), 'utf8').split(/\r?\n/).find((l) => l.startsWith(`${name}=`))
    return line?.slice(name.length + 1).trim().replace(/^["']|["']$/g, '')
  } catch {
    return undefined
  }
}

// Same shape as gbpKey() in services/gbp.service.ts and STORE_KEY in
// config/store.ts (not imported: they pull in next/cache and env handling).
const store = env('NEXT_PUBLIC_STORE_KEY')?.trim().toLowerCase() || 'onsite'
const key = (kind, id) => ['oss-next', store, 'gbp', kind, ...(id ? [id] : [])].join(':')
const keys = [...GBP_PAGES.map((page) => key('page', page.slug)), key('shared'), key('template')]

const rawUrl = env('NEXT_UPSTASH_REDIS_REST_URL')
const token = env('NEXT_UPSTASH_REDIS_REST_TOKEN')

// One MGET over Upstash's REST API, with one retry: the build reads Redis for
// the pages straight after this, so a slow answer is worth a second try.
async function readAll() {
  const url = /^https?:\/\//i.test(rawUrl) ? rawUrl : `https://${rawUrl}`
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, {
        method: 'POST',
        headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
        body: JSON.stringify(['MGET', ...keys]),
        signal: AbortSignal.timeout(10_000),
      })
      if (!res.ok) throw new Error(`HTTP ${res.status}`)
      const { result } = await res.json()
      if (!Array.isArray(result) || result.length !== keys.length) throw new Error('unexpected MGET answer')
      return result
    } catch (error) {
      if (attempt === 2) throw error
      await new Promise((resolve) => setTimeout(resolve, 1000))
    }
  }
}

const target = new URL('../lib/data/gbpSnapshot.ts', import.meta.url)

try {
  if (!rawUrl || !token) throw new Error('Redis is not configured')
  const values = await readAll()
  const records = {}
  values.forEach((value, i) => {
    if (typeof value !== 'string') return
    // Records are envelopes, { data, updatedAt, updatedBy } (services/gbp.service.ts).
    const record = JSON.parse(value)
    if (record && typeof record === 'object' && 'data' in record) records[keys[i]] = record.data
  })

  const out = `// GENERATED by scripts/generate-gbp-snapshot.mjs from Redis, before the build.
// Do not edit by hand. The checked-in copy is an empty stub; Vercel builds fill it.

/** When the records below were read, or null for the stub. */
export const GBP_SNAPSHOT_TAKEN_AT: string | null = ${JSON.stringify(new Date().toISOString())}

/**
 * The GBP pages' published records by Redis key, \`data\` only, as of the
 * last build: the fallback while Redis is unreachable (services/gbp.service.ts).
 */
export const GBP_SNAPSHOT: Readonly<Record<string, unknown>> = ${JSON.stringify(records, null, 2)}
`
  writeFileSync(target, out)
  console.log(`lib/data/gbpSnapshot.ts: ${Object.keys(records).length} of ${keys.length} record(s), store "${store}"`)
} catch (error) {
  console.warn(`lib/data/gbpSnapshot.ts: left as it is (${error instanceof Error ? error.message : error}); the fallback is the code seed`)
}
