// Writes config/depotCoordinates.ts: a copy of every depot record the backend
// serves at /api/depots/ (all of them, every field), as of the last dev start
// or build.
//
// Why: the depots come from the backend (services/depot.service.ts). This copy
// is what the site falls back to when the backend cannot be reached, so the
// ZIP lookup, "use my current location" and /api/depots keep working through
// an outage. It is server-only: browser code asks the server for the nearest
// depot rather than importing the list.
//
// Runs before `next dev` and `next build` (package.json). Never fails either:
// if the backend cannot be read, the file is left as it is. The file is only
// rewritten when the depot data changed, so a dev start does not dirty git.
import { readFileSync, writeFileSync } from 'node:fs'

function env(name) {
  if (process.env[name]) return process.env[name]
  try {
    const line = readFileSync(new URL('../.env.local', import.meta.url), 'utf8').split(/\r?\n/).find((l) => l.startsWith(`${name}=`))
    return line?.slice(name.length + 1).trim().replace(/^["']|["']$/g, '')
  } catch {
    return undefined
  }
}

const backend = (env('NEXT_OSS_BACKEND_URL') ?? '').replace(/\/+$/, '')
const key = env('NEXT_OSS_BACKEND_KEY')
const target = new URL('../config/depotCoordinates.ts', import.meta.url)

async function readAll() {
  const depots = []
  let next = `${backend}/api/depots/?page_size=200`
  for (let page = 0; next && page < 10; page++) {
    const res = await fetch(next, {
      headers: { Accept: 'application/json', ...(key ? { Authorization: `Api-Key ${key}` } : {}) },
      signal: AbortSignal.timeout(15_000),
    })
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    const body = await res.json()
    if (!Array.isArray(body?.results)) throw new Error('unexpected answer')
    depots.push(...body.results)
    next = body.next
  }
  if (!depots.length) throw new Error('no depots')
  return depots
}

try {
  if (!backend) throw new Error('NEXT_OSS_BACKEND_URL is not set')
  const depots = (await readAll()).sort((a, b) => a.id - b.id)
  const records = `[\n${depots.map((d) => `  ${JSON.stringify(d)},`).join('\n')}\n]`

  let current = ''
  try {
    current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n')
  } catch {}
  if (current.includes(`export const DEPOT_SNAPSHOT: readonly Depot[] = ${records}\n`)) {
    console.log(`config/depotCoordinates.ts: unchanged (${depots.length} depots)`)
  } else {
    writeFileSync(
      target,
      `// GENERATED by scripts/generate-depot-coordinates.mjs from the backend's /api/depots/.
// Do not edit by hand; it is refreshed before every dev start and build.
// Server-only: the fallback when the backend's depot list cannot be read
// (services/depot.service.ts). Browser code asks the server instead.
import type { Depot } from '@/types/depot'

/** When the records below were read from the backend. */
export const DEPOT_SNAPSHOT_TAKEN_AT = ${JSON.stringify(new Date().toISOString())}

/** Every depot the backend served, every field, sorted by id. */
export const DEPOT_SNAPSHOT: readonly Depot[] = ${records}
`,
    )
    console.log(`config/depotCoordinates.ts: ${depots.length} depots written`)
  }
} catch (error) {
  console.warn(`config/depotCoordinates.ts: left as it is (${error instanceof Error ? error.message : error}); the fallback is the last copy`)
}
