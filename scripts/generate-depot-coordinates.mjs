// Writes config/depotCoordinates.ts: title, latitude and longitude of every
// active depot, taken from config/locations.ts.
//
// Why: client components find the visitor's nearest depot, and importing
// config/locations.ts for that shipped every depot record (hours, rates, JSON
// blobs: ~220 KB of source) to the browser on every page, through
// ZipAutoDetect in the root layout. The client needs three fields of each.
//
// Runs before `next dev` and `next build` (package.json), so the table cannot
// drift from the records. Node strips the type-only import in locations.ts.
import { readFileSync, writeFileSync } from 'node:fs'

const { LOCATIONS } = await import('../config/locations.ts')

const rows = LOCATIONS
  .filter((l) => l.is_disabled === '0')
  .map((l) => [l.title, Number(l.lat), Number(l.lng)])
  .filter(([, lat, lng]) => Number.isFinite(lat) && Number.isFinite(lng))

const out = `// GENERATED by scripts/generate-depot-coordinates.mjs from config/locations.ts.
// Do not edit by hand; it is rewritten before every dev start and build.

/** [title, latitude, longitude] of every active depot. Safe for client bundles. */
export const DEPOT_COORDINATES: readonly (readonly [string, number, number])[] = [
${rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}
]
`

const target = new URL('../config/depotCoordinates.ts', import.meta.url)
let current = ''
try {
  current = readFileSync(target, 'utf8')
} catch {}
if (current.replace(/\r\n/g, '\n') !== out) writeFileSync(target, out)
console.log(`config/depotCoordinates.ts: ${rows.length} depot(s)`)
