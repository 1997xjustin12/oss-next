// Writes lib/data/locationSnapshot.ts: the location pages' published records
// (the template and every native location) as Redis holds them at build time.
//
// Why: when Redis is unreachable, the location pages fall back. Without this the
// fallback is the code records (lib/data/locationPage*.ts), only as current as
// their last commit, so edits published in /admin/location-pages since then
// would vanish during an outage. With it, the fallback is the published content
// as of the last deploy; the code records stay the last resort
// (services/locationPage.service.ts). The same arrangement as the GBP pages'
// (scripts/generate-gbp-snapshot.mjs).
//
// Runs before `next build` (package.json), but only on Vercel or with
// LOCATION_SNAPSHOT=1: the checked-in file is the empty stub. Never fails the
// build: if Redis can't be read, the file is left as it is.
import { readFileSync, writeFileSync } from 'node:fs'

if (!process.env.VERCEL && process.env.LOCATION_SNAPSHOT !== '1') {
  console.log('lib/data/locationSnapshot.ts: skipped (not on Vercel; LOCATION_SNAPSHOT=1 to force)')
  process.exit(0)
}

const { LOCATION_PAGE_SLUGS } = await import('../lib/data/locationPageSlugs.ts')

function env(name) {
  if (process.env[name]) return process.env[name]
  try {
    const line = readFileSync(new URL('../.env.local', import.meta.url), 'utf8').split(/\r?\n/).find((l) => l.startsWith(`${name}=`))
    return line?.slice(name.length + 1).trim().replace(/^["']|["']$/g, '')
  } catch {
    return undefined
  }
}

// Same shape as locationKey() in services/locationPage.service.ts and STORE_KEY
// in config/store.ts (not imported: they pull in next/cache and env handling).
const store = env('NEXT_PUBLIC_STORE_KEY')?.trim().toLowerCase() || 'onsite'
const key = (kind, id) => ['oss-next', store, 'location', kind, ...(id ? [id] : [])].join(':')
const keys = [key('template'), ...LOCATION_PAGE_SLUGS.map((slug) => key('page', slug))]

const rawUrl = env('NEXT_UPSTASH_REDIS_REST_URL')
const token = env('NEXT_UPSTASH_REDIS_REST_TOKEN')

// One MGET over Upstash's REST API, with one retry.
async function readAll() {
  const url = /^https?:\/\//i.test(rawUrl) ? rawUrl : `https://${rawUrl}`
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, {
        method: 'POST',
        headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
        body: JSON.stringify(['MGET', ...keys]),
        signal: AbortSignal.timeout(10_000),
      })
      if (!res.ok) throw new Error(`HTTP ${res.status}`)
      const { result } = await res.json()
      if (!Array.isArray(result) || result.length !== keys.length) throw new Error('unexpected MGET answer')
      return result
    } catch (error) {
      if (attempt === 2) throw error
      await new Promise((resolve) => setTimeout(resolve, 1000))
    }
  }
}

const target = new URL('../lib/data/locationSnapshot.ts', import.meta.url)

try {
  if (!rawUrl || !token) throw new Error('Redis is not configured')
  const values = await readAll()
  const records = {}
  values.forEach((value, i) => {
    if (typeof value !== 'string') return
    // Records are envelopes, { data, updatedAt, updatedBy } (services/locationPage.service.ts).
    const record = JSON.parse(value)
    if (record && typeof record === 'object' && 'data' in record) records[keys[i]] = record.data
  })

  const out = `// GENERATED by scripts/generate-location-snapshot.mjs from Redis, before the build.
// Do not edit by hand. The checked-in copy is an empty stub; Vercel builds fill it.

/** When the records below were read, or null for the stub. */
export const LOCATION_SNAPSHOT_TAKEN_AT: string | null = ${JSON.stringify(new Date().toISOString())}

/**
 * The location pages' published records by Redis key, \`data\` only, as of the
 * last build: the fallback while Redis is unreachable (services/locationPage.service.ts).
 */
export const LOCATION_SNAPSHOT: Readonly<Record<string, unknown>> = ${JSON.stringify(records, null, 2)}
`
  writeFileSync(target, out)
  console.log(`lib/data/locationSnapshot.ts: ${Object.keys(records).length} of ${keys.length} record(s), store "${store}"`)
} catch (error) {
  console.warn(`lib/data/locationSnapshot.ts: left as it is (${error instanceof Error ? error.message : error}); the fallback is the code records`)
}
